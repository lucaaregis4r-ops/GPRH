function applyTimeMetadata() {
  [...RH_DISCOVERY_ACTIONS, ...RH_INTERVENTION_ACTIONS].forEach((action) => {
    action.tempo = { ...timePresetForAction(action) };
  });
}

function timePresetForAction(action) {
  if (
    [
      "pesquisa_clima_simples",
      "auditoria_acumulo_desvio",
      "redistribuir_funcoes",
      "formalizar_funcao_informal",
      "alinhar_lideranca",
      "reforcar_canal_denuncia",
      "investigar_denuncia",
      "aplicar_acao_corretiva",
      "planejar_reposicao",
      "plano_desenvolvimento_simples",
    ].includes(action.tipo)
  ) {
    return action.requerAprovacaoDiretoria || action.alvo === "denuncia" ? TIME_PRESETS.projeto_sensivel : TIME_PRESETS.projeto;
  }

  if (["conversa_individual_profunda", "responder_pedido_conversa", "responder_pedido_carreira"].includes(action.tipo)) {
    return TIME_PRESETS.conversa_profunda;
  }

  if (action.alvo === "setor" || action.tipo === "priorizar_tarefas_criticas" || action.tipo === "conter_rumor") {
    return TIME_PRESETS.setor;
  }

  return TIME_PRESETS.conversa_curta;
}

function getRhActionDefinition(type) {
  return [...RH_DISCOVERY_ACTIONS, ...RH_INTERVENTION_ACTIONS].find((action) => action.tipo === type) || null;
}

